/**
 * Initialize peripheral pads.
 *
 * @return Execution status.
 */
int imx_init_pads(imx_startup_data_t *startup_data)
{
    do {
#if IMX_ENET_INIT_ENABLED
        /* Configure ENET0 QoS pads */
        if (imx_init_enet0_pads() != 0) {
            break;
        }
        /* Configure ENET1 FEC pads */
        if (imx_init_enet1_pads() != 0) {
            break;
        }
#endif
#if IMX_USB_INIT_ENABLED
        /* Configure USB pads */
        if (imx_init_usb_pads() != 0) {
            break;
        }
#endif
#if IMX_USDHC_INIT_ENABLED
#if 0
        /* Configure USDHC pads */
        if (imx_init_usdhc1_pads() != 0) {
            break;
        }
#endif
        /* Configure USDHC pads */
        if (imx_init_usdhc2_pads() != 0) {
            break;
        }
        /* Configure USDHC pads */
        if (imx_init_usdhc3_pads() != 0) {
            break;
        }
#endif
#if IMX_ECSPI_INIT_ENABLED
        /* Configure ECSPI pads */
        if (imx_init_ecspi_pads() != 0) {
            break;
        }
#endif
#if IMX_QSPI_INIT_ENABLED
        /* Configure QSPI pads */
        if (imx_init_qspi_pads() != 0) {
            break;
        }
#endif
#if IMX_NAND_INIT_ENABLED
        /* Configure NAND pads */
        if (nand_enable) {
            if (imx_init_nand_pads() != 0) {
                break;
            }
        }
#endif
#if IMX_FLEXCAN_INIT_ENABLED
        /* Configure FlexCAN pads */
        if (imx_init_flexcan_pads() != 0) {
            break;
        }
#endif
#if IMX_UART_INIT_ENABLED
        /* Configure LPUART pads */
        if (imx_init_uart_pads() != 0) {
            break;
        }
#endif
#if IMX_AUDIO_INIT_ENABLED
        /* Configure Audio pads */
        if (imx_init_audio_pads() != 0) {
            break;
        }
#endif
#if IMX_GPIO_INIT_ENABLED
        if (imx_init_gpio_pads() != 0) {
            break;
        }
#endif
#if IMX_PCIE_INIT_ENABLED
        /* Configure PCIe pads */
        if (imx_init_pcie_pads() != 0) {
            break;
        }
#endif

#if IMX_MIPI_CSI_INIT_ENABLED
        /* Configure PCIe pads */
        if (imx_init_mipi_csi_pads() != 0) {
            break;
        }
#endif
#if IMX_DC_INIT_ENABLED
        /* Configure display related pads */
        if (imx_init_display_pads() != 0) {
            break;
        }
#endif
        return 0;
    } while (0);
    return -1;
}

